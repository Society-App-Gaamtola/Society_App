-- ---------- Money ----------

CREATE TABLE donations (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  donor_user_id BIGINT        NULL,     -- a member; or donor_name for someone who isn't (entered in the panel)
  donor_name    VARCHAR(128)  NULL,
  amount        NUMERIC(12,2) NOT NULL,
  purpose       VARCHAR(128)  NULL,
  method        VARCHAR(8)    NOT NULL CHECK (method IN ('gateway', 'upi_app', 'upi_qr', 'cash', 'bank', 'cheque')),
  status        VARCHAR(16)   NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'success', 'failed', 'cancelled', 'rejected')), -- success = verified
  reference_no  VARCHAR(64)   NULL,
  donated_on    DATE          NOT NULL DEFAULT CURRENT_DATE, -- the day it counts on (totals, reports)
  proof_url     VARCHAR(512)  NULL,     -- payment screenshot / slip (Cloudinary)
  confirmed_at  TIMESTAMPTZ   NULL,
  verified_by   BIGINT        NULL,     -- who verified or rejected it
  entered_by    BIGINT        NULL,     -- who typed it in the panel (null = the member, from the app)
  note          VARCHAR(256)  NULL,
  is_active     SMALLINT      NOT NULL DEFAULT 1,
  is_deleted    SMALLINT      NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  CONSTRAINT fk_donations_donor FOREIGN KEY (donor_user_id) REFERENCES users (id),
  CONSTRAINT fk_donations_entered_by FOREIGN KEY (entered_by) REFERENCES users (id),
  CONSTRAINT fk_donations_verified_by FOREIGN KEY (verified_by) REFERENCES users (id),
  CONSTRAINT ck_donations_donor CHECK (donor_user_id IS NOT NULL OR donor_name IS NOT NULL)
);
CREATE INDEX idx_donations_donated_on ON donations (donated_on);
CREATE INDEX idx_donations_verified_by ON donations (verified_by);
CREATE INDEX idx_donations_donor ON donations (donor_user_id);
CREATE INDEX idx_donations_status_confirmed ON donations (status, confirmed_at);
CREATE INDEX idx_donations_entered_by ON donations (entered_by);
-- A UPI transaction ID (UTR) can be claimed only once
CREATE UNIQUE INDEX uq_donations_upi_reference ON donations (reference_no)
  WHERE method IN ('upi_app', 'upi_qr') AND is_deleted = 0;

