-- Society App – PostgreSQL schema (all 24 tables).
-- Run on an empty database:  psql -U postgres -d society_app -f database/schema.sql
-- Then add the reference rows:  psql -U postgres -d society_app -f database/seed.sql
--
-- Conventions
--   * Dates and times are TIMESTAMPTZ; the backend sets each session to Indian time (constant.DB_TIME_ZONE),
--     so NOW(), CURRENT_DATE and ::date all follow IST.
--   * 0 / 1 flags are SMALLINT, so the API keeps returning 0 / 1.
--   * Fixed lists of values are VARCHAR + CHECK (easy to extend with ALTER TABLE ... DROP/ADD CONSTRAINT).
--   * updated_at is refreshed by the set_updated_at() trigger on every UPDATE.
--   * Text is stored in one language (English). No name_hi / name_gu style columns: translations live in
--     backend/languages/*.js and are looked up with common.translate().
--   * Only the email is verified (by OTP). There is no mobile verification.

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------- Users and access ----------

CREATE TABLE roles (
  id         BIGINT      PRIMARY KEY,
  code       VARCHAR(32) NOT NULL,
  name       VARCHAR(64) NOT NULL,
  is_active  SMALLINT    NOT NULL DEFAULT 1,
  is_deleted SMALLINT    NOT NULL DEFAULT 0,
  CONSTRAINT uq_roles_code UNIQUE (code)
);

CREATE TABLE users (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_code        VARCHAR(32)  NULL,
  role_id            BIGINT       NOT NULL DEFAULT 3,
  full_name          VARCHAR(128) NULL,
  country_code       VARCHAR(8)   NOT NULL DEFAULT '+91',
  mobile             VARCHAR(16)  NOT NULL,
  email              VARCHAR(256) NOT NULL,
  password_hash      VARCHAR(256) NOT NULL,
  email_verified_at  TIMESTAMPTZ  NULL,
  preferred_language VARCHAR(2)   NOT NULL DEFAULT 'en'
    CHECK (preferred_language IN ('en', 'hi', 'gu')),
  signup_step        VARCHAR(16)  NOT NULL DEFAULT 'otp_pending'
    CHECK (signup_step IN ('otp_pending', 'profile_pending', 'completed')),
  status             VARCHAR(16)  NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
  is_active          SMALLINT     NOT NULL DEFAULT 1,
  is_deleted         SMALLINT     NOT NULL DEFAULT 0,
  last_login_at      TIMESTAMPTZ  NULL,
  failed_login_count SMALLINT     NOT NULL DEFAULT 0,
  locked_until       TIMESTAMPTZ  NULL,
  created_by         BIGINT       NULL,
  created_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_users_mobile UNIQUE (country_code, mobile),
  CONSTRAINT uq_users_member_code UNIQUE (member_code),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles (id),
  CONSTRAINT fk_users_created_by FOREIGN KEY (created_by) REFERENCES users (id)
);
CREATE INDEX idx_users_role ON users (role_id);
CREATE INDEX idx_users_created_by ON users (created_by);

