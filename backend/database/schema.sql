-- ---------- Translations of content (config/translator.js) ----------
-- The original text stays in its own table (events.title, notices.body…). When an event / notice is saved, its text
-- is translated into every other app language and kept here, one row per item + language + field. source_hash is the
-- sha256 of the original it was made from: when the original changes, the row is translated again
CREATE TABLE content_translations (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type VARCHAR(16) NOT NULL CHECK (entity_type IN ('event', 'notice')),
  entity_id   BIGINT      NOT NULL,
  lang        VARCHAR(2)  NOT NULL,
  field       VARCHAR(32) NOT NULL,
  value       TEXT        NOT NULL,
  source_hash CHAR(64)    NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_content_translations UNIQUE (entity_type, entity_id, lang, field)
);
CREATE INDEX idx_content_translations_entity ON content_translations (entity_type, entity_id, lang);

-- ---------- updated_at triggers (MySQL's ON UPDATE CURRENT_TIMESTAMP) ----------
DO $$
DECLARE t TEXT;
BEGIN
  FOR t IN
    SELECT table_name FROM information_schema.columns
    WHERE table_schema = 'public' AND column_name = 'updated_at'
  LOOP
    EXECUTE format('CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON %1$I FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t);
  END LOOP;
END $$;
